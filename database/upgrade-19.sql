CREATE TABLE IF NOT EXISTS provinces (
    id INT UNSIGNED NOT NULL PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS towns (
    id INT UNSIGNED NOT NULL PRIMARY KEY,
    province_id INT UNSIGNED NOT NULL,
    name VARCHAR(120) NOT NULL,
    latitude DECIMAL(9,6) NOT NULL,
    longitude DECIMAL(9,6) NOT NULL,
    coordinate_source VARCHAR(30) NOT NULL,
    attribution VARCHAR(255) NOT NULL,
    UNIQUE KEY uq_town_province_name (province_id,name),
    CONSTRAINT fk_town_province FOREIGN KEY (province_id) REFERENCES provinces(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
ALTER TABLE companies
    ADD COLUMN IF NOT EXISTS physical_address VARCHAR(255) DEFAULT NULL,
    ADD COLUMN IF NOT EXISTS town_id INT UNSIGNED DEFAULT NULL,
    ADD COLUMN IF NOT EXISTS latitude DECIMAL(9,6) DEFAULT NULL,
    ADD COLUMN IF NOT EXISTS longitude DECIMAL(9,6) DEFAULT NULL,
    ADD COLUMN IF NOT EXISTS accuracy_m DECIMAL(10,2) DEFAULT NULL,
    ADD COLUMN IF NOT EXISTS location_precision ENUM('town','exact') DEFAULT NULL,
    ADD COLUMN IF NOT EXISTS location_source ENUM('town_seed','employer_pin','employer_gps_once','admin','pasted_link') DEFAULT NULL,
    ADD COLUMN IF NOT EXISTS location_review_status ENUM('none','pending','approved','rejected') NOT NULL DEFAULT 'none',
    ADD COLUMN IF NOT EXISTS location_updated_at DATETIME DEFAULT NULL,
    ADD COLUMN IF NOT EXISTS location_approved_at DATETIME DEFAULT NULL,
    ADD COLUMN IF NOT EXISTS landmark_directions VARCHAR(300) DEFAULT NULL,
    ADD INDEX IF NOT EXISTS ix_companies_town (town_id),
    ADD INDEX IF NOT EXISTS ix_companies_coordinates (latitude,longitude),
    ADD CONSTRAINT fk_companies_town FOREIGN KEY IF NOT EXISTS (town_id) REFERENCES towns(id);
CREATE TABLE IF NOT EXISTS company_location_proposals (
    company_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
    details JSON NOT NULL,
    CONSTRAINT fk_company_location_proposal FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
ALTER TABLE openings
    ADD COLUMN IF NOT EXISTS accommodation ENUM('yes','no','unknown') NOT NULL DEFAULT 'unknown',
    ADD COLUMN IF NOT EXISTS transport_allowance ENUM('yes','no','unknown') NOT NULL DEFAULT 'unknown',
    ADD COLUMN IF NOT EXISTS meal_allowance ENUM('yes','no','unknown') NOT NULL DEFAULT 'unknown',
    ADD COLUMN IF NOT EXISTS remote_option ENUM('no','hybrid','remote') NOT NULL DEFAULT 'no';
