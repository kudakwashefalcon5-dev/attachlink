ALTER TABLE users
 ADD COLUMN IF NOT EXISTS email_verified_at DATETIME NULL DEFAULT CURRENT_TIMESTAMP,
 ADD COLUMN IF NOT EXISTS password_changed_at DATETIME(6) NULL;
ALTER TABLE users ALTER COLUMN email_verified_at SET DEFAULT NULL;
ALTER TABLE student_preferences ADD COLUMN IF NOT EXISTS email_notifications TINYINT(1) NOT NULL DEFAULT 1;

CREATE TABLE IF NOT EXISTS employer_preferences (
 user_id BIGINT UNSIGNED PRIMARY KEY,
 email_notifications TINYINT(1) NOT NULL DEFAULT 1,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS email_outbox (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 recipient VARCHAR(190) NOT NULL,
 subject VARCHAR(255) NOT NULL,
 body TEXT NOT NULL,
 attempts INT UNSIGNED NOT NULL DEFAULT 0,
 next_attempt_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 sent_at DATETIME NULL,
 failed_at DATETIME NULL,
 expires_at DATETIME NULL,
 INDEX (sent_at,failed_at,next_attempt_at,id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS password_resets (
 token_hash CHAR(64) CHARACTER SET ascii PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 expires_at DATETIME NOT NULL,
 used_at DATETIME NULL,
 requested_ip VARCHAR(45) NOT NULL,
 INDEX (user_id,used_at),
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS email_verifications (
 token_hash CHAR(64) CHARACTER SET ascii PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 expires_at DATETIME NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS admin_audit_log (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 admin_id BIGINT UNSIGNED NOT NULL,
 action VARCHAR(64) NOT NULL,
 target_type VARCHAR(64) NOT NULL,
 target_id BIGINT UNSIGNED NULL,
 detail TEXT NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX (action,id),
 INDEX (target_type,id)
) ENGINE=InnoDB;
